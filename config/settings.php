 *
 * 3. **键名必须能与环境变量名互相推导**。规则是「点号转下划线并大写」：
 *    key_pool.default_rpm → KEY_POOL_DEFAULT_RPM
 *    若某天要让 .env 覆盖它，必须保证能推出这个名字。
 *
 * 分组（顶层的键）不是纯装饰：后台配置页按这个分组折叠展示，
 * 因此新增配置项时请放进合适的组，而不是都堆在顶层。
 */

