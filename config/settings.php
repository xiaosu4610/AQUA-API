<?php
/**
 * 配置项默认值（代码级，只读）
 *
 * 这里定义的是「开箱即用的默认值」，也是配置的最终回退层。
 * 取值优先级完整链路（见 app/common/Settings.php）：
 *
 *     进程缓存 → options 表 → 环境变量(.env) → 本文件 → 调用方传入的默认值
 *
 * 为什么要单独有这么一层，而不是直接把默认值写在调用处：
 *   1. 后台可以展示「默认值 vs 当前值」，站长一眼看出哪些被改过；
 *   2. 需要「恢复默认」时，删掉数据库里那一行即可，不用去翻代码里散落的常量；
 *   3. 所有可调项集中在一处，便于对照文档。
 *
 * 注意：这里**只放可以公开的默认值**。任何密钥、密码都不允许出现在本文件。
 */

declare(strict_types=1);

return [
    // ── 站点 ─────────────────────────────────────────────
    'site' => [
        // 站点名称，展示在后台标题与后续的首页
        'name' => 'aqua-api-php',

        // 站点模式：
        //   commercial      商业站：显示定价、充值等入口
        //   public_welfare  公益站：隐藏计费入口，改为「赞助」入口，并默认收紧限流
        'mode' => 'commercial',
    ],

    // ── 上游：NVIDIA NIM ──────────────────────────────────
    'nim' => [
        'base_url' => 'https://integrate.api.nvidia.com/v1',

        // 单个 Key 在单个模型上的每分钟请求上限。
        // NIM 免费层官方口径约 40 RPM/模型。
        'rpm_limit' => 40,

        // 超时分层（秒）。刻意分成三个而不是一个：
        //   ttft  —— 首字节超时：判断上游是否「根本没响应」，用于触发换 Key 重试
        //   idle  —— 空闲超时：两个数据块之间的最大间隔，长回答不会因此被杀
        //   total —— 总时长上限：兜底保护
        'ttft_timeout' => 30,
        'idle_timeout' => 60,
        'total_timeout' => 600,
    ],

    // ── 会话 ─────────────────────────────────────────────
    // 键名刻意定为 session.secure 而不是 security.session_secure ——
    // 因为环境变量的映射规则是「点号转下划线并大写」，
    // 只有 session.secure 才能正确映射到 .env 里的 SESSION_SECURE
    // （config/session.php 读的正是这个变量名）。
    // 配置键与环境变量名保持一致，可以避免「改了 .env 却读不到」这类困惑。
    'session' => [
        // 会话 Cookie 是否只允许 HTTPS 传输。
        // 生产必须为 true；本地用 http://127.0.0.1 开发时需在 .env 里设为 false，
        // 否则浏览器不会保存 Cookie、登录态无法保持。
        'secure' => true,
    ],
];
