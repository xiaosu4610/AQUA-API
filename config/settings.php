<?php
/**
 * 配置项默认值（代码级，只读）
 *
 * 这里定义的是「开箱即用的默认值」，也是配置的最终回退层。
 * 取值优先级完整链路（见 app/common/Settings.php）：
 *
 *     进程缓存 → options 表 → 环境变量(.env) → 本文件 → 调用方传入的默认值
 *
 * 为什么要单独有这么一层，而不是直接把默认值写在调用处：
 *   1. 后台可以展示「默认值 vs 当前值」，站长一眼看出哪些被改过；
 *   2. 需要「恢复默认」时，删掉数据库里那一行即可，不用去翻代码里散落的常量；
 *   3. 所有可调项集中在一处，便于对照文档。
 *
 * ═══ 三条必须遵守的约定 ═══
 *
 * 1. **只放可以公开的默认值**。任何密钥、密码都不允许出现在本文件。
 *
 * 2. **类型即契约**。写 `true` 就是布尔、写 `40` 就是整数 ——
 *    类型由这里的字面量决定（见 Settings::coerce()），
 *    它同时决定后台渲染成复选框还是输入框。写错类型会导致
 *    「存了字符串 '0' 却被当成真」这类极难排查的 bug。
 *
 * 3. **键名必须能与环境变量名互相推导**。规则是「点号转下划线并大写」：
 *    key_pool.default_rpm → KEY_POOL_DEFAULT_RPM
 *    若某天要让 .env 覆盖它，必须保证能推出这个名字。
 *
 * 分组（顶层的键）不是纯装饰：后台配置页按这个分组折叠展示，
 * 因此新增配置项时请放进合适的组，而不是都堆在顶层。
 */

declare(strict_types=1);

return [
    // ═══════════════════════════════════════════════════════
    // 站点
    // ═══════════════════════════════════════════════════════
    'site' => [
        // 站点名称，展示在后台标题与首页
        'name' => 'aqua-api-php',

        // 站点模式：
        //   commercial      商业站：显示定价、充值等入口
        //   public_welfare  公益站：隐藏计费入口，改为「赞助」入口，并默认收紧限流
        'mode' => 'commercial',

        // 首页的一句话介绍。留空则用代码里写死的默认文案
        'description' => '',

        // 站点公告。非空时会在首页与后台顶部显示，用于临时通知（维护、限流等）
        'announcement' => '',

        // 备案号。境内服务器必须展示，否则有被通报的风险
        'icp' => '',

        // 页脚署名。留空则显示开源项目名
        'footer' => '',
    ],

    // ═══════════════════════════════════════════════════════
    // 网关（转发行为）
    // ═══════════════════════════════════════════════════════
    'gateway' => [
        // 与上游建立连接的超时（秒）。这个值只覆盖 TCP/TLS 握手，
        // 不覆盖「模型思考时间」—— 后者由 ttft_timeout 管
        'connect_timeout' => 8,

        // 探测类请求（测活、拉模型清单）的总超时（秒）。
        // 刻意比正式转发短：测活是给人看的，宁可快速失败
        'probe_timeout' => 20,

        // ── 流式转发的超时分层 ──
        // 分三个而不是一个，是因为它们的职责完全不同：
        //   ttft —— 首字节超时：判断上游是否「根本没响应」。
        //           这是唯一适合用来「换 Key 重试」的判据
        //   idle —— 空闲超时：两个数据块之间的最大间隔。
        //           长回答不会因为总时长而中途中止，只会因为「卡住不动」被中止
        //   total —— 总时长兜底：防止一个连接被永久占住
        'ttft_timeout' => 30,
        'idle_timeout' => 60,
        'total_timeout' => 600,

        // 单个请求最多重试几次（换渠道 / 换 Key 都算一次重试）。
        // 设为 0 表示不重试，失败直接返回给调用方
        'max_retries' => 2,

        // 哪些上游状态码值得重试（逗号分隔）。
        // 429 与 5xx 属于「换一个渠道可能就好了」；401/403 是凭据问题，重试无意义
        'retry_status' => '429,500,502,503,504',

        // SSE 心跳间隔（秒）。经过 Nginx 等反代时，
        // 长时间没有数据流动的连接会被中间设备掐断 —— 必须靠心跳保活，
        // 而不是调大超时（详见项目文档里「长连接 5 分钟掉线」那一条）
        'heartbeat_interval' => 15,
    ],

    // ═══════════════════════════════════════════════════════
    // 密钥池（多 Key 轮换与健康治理）
    // ═══════════════════════════════════════════════════════
    'key_pool' => [
        // 单把 Key 的默认每分钟请求上限。
        // 渠道的 rpm_limit 与单把 Key 的 rpm_limit 都为 0 时才用它。
        // NIM 免费层官方口径约 40 RPM/模型
        'default_rpm' => 40,

        // 连续失败多少次后自动停用该 Key。
        // 注意只统计**瞬时失败**（429/5xx/网络抖动）；
        // 认定凭据失效（401/403）时是立即停用，不看这个阈值
        'fail_threshold' => 5,

        // 是否允许「达到失败阈值后自动停用」。关掉后只计数不停用，
        // 适合排查阶段（避免误停导致可用 Key 越用越少）
        'auto_disable' => true,

        // 自动停用后的冷却秒数：到期自动恢复启用，再给一次机会。
        // 设为 0 表示不自动恢复（需人工启用）
        'cooldown_seconds' => 600,
    ],

    // ═══════════════════════════════════════════════════════
    // 安全
    // ═══════════════════════════════════════════════════════
    'security' => [
        // 后台登录连续失败多少次后锁定。
        // 后台只有一个入口且不需要用户名，没有锁定等于把门敞开
        'login_max_attempts' => 5,

        // 锁定时长（分钟）
        'login_lock_minutes' => 15,

        // 后台登录态的最长有效时长（分钟）。超过后强制重新登录。
        //
        // 为什么不直接改会话本身的 lifetime：
        //   那是「会话数据在服务器上存活多久」，属于存储层参数，
        //   在 config/session.php 里、进程启动时读一次；
        //   而这里是「管理员多久必须重新输一次密码」，属于安全策略，
        //   由中间件在每个请求上判定 —— 因此后台改完立刻生效。
        //   两者混为一谈会导致「后台改了没反应」的困惑。
        'admin_session_minutes' => 120,
    ],

    // ═══════════════════════════════════════════════════════
    // 会话
    // ═══════════════════════════════════════════════════════
    // 键名刻意定为 session.secure 而不是 security.session_secure ——
    // 因为环境变量的映射规则是「点号转下划线并大写」，
    // 只有 session.secure 才能正确映射到 .env 里的 SESSION_SECURE
    // （config/session.php 读的正是这个变量名）。
    // 配置键与环境变量名保持一致，可以避免「改了 .env 却读不到」这类困惑。
    'session' => [
        // 会话 Cookie 是否只允许 HTTPS 传输。
        // 生产必须为 true；本地用 http://127.0.0.1 开发时需在 .env 里设为 false，
        // 否则浏览器不会保存 Cookie、登录态无法保持。
        'secure' => true,
    ],
];
