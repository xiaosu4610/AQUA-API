-- 迁移 0018：调用日志记录"上游实际模型名"
--
-- 背景（为什么必须有它）：
--   渠道级模型映射（见 0016）让"对外模型名"与"上游模型名"解耦。转发层据此把
--   请求里的 model 改写后再发上游，客户端看到的仍是自己的对外名。但这样一来，
--   排查问题时无法从日志看出"这条请求实际打到了上游的哪个模型"——
--   例如对外 gpt-4o 可能被映射到上游 nvidia/llama-3.1-70b，日志里只有 gpt-4o。
--   本迁移新增一列记录上游实际使用的模型名，让"映射是否按预期生效"可被直接审计。
--
-- 设计说明：
--   1) upstream_model 默认空串，表示"上游模型与对外模型一致"（未配置映射，
--      或映射结果与原模型名相同）。语义约定为"空即未改写"，而不是重复存一遍
--      model 列——绝大多数行不经过映射，重复存同一名字只会让日志变长且难读；
--   2) 不建索引：该列只用于人工排查与展示，不参与筛选/聚合，建索引反而增加写入放大
--      （usage_logs 是高频写入表，索引越少越好，参见 0003 的同类取舍）；
--   3) 列的位置紧邻 model，便于人工核对"对外名 / 上游名"这一对值。
--
-- 兼容性：
--   本列 NOT NULL + 常量默认值，SQLite 允许对已有表直接 ADD COLUMN；
--   已有日志行会一次性获得空串默认值，读取与统计行为与迁移前完全一致。

ALTER TABLE usage_logs ADD COLUMN upstream_model TEXT NOT NULL DEFAULT '';
