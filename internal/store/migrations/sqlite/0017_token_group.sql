-- 迁移 0017：访问令牌的所属分组
--
-- 背景（为什么必须有它）：
--   分组已是本网关的一等实体：渠道归属于分组，计价规则也按分组区分
--   （见 0011_model_groups.sql）。但"下游凭证"——访问令牌——还没有分组归属，
--   于是所有令牌都只能走同一套渠道与价格，无法做到"给不同人群不同的上游与价格"。
--   本迁移给令牌补上所属分组，使"用哪把密钥就走哪个分组"成为可能。
--
-- 设计说明：
--   1) group_name 默认空串，表示"使用网关默认分组"。
--      默认值刻意不写死为 'default'：历史令牌落库后必须保持原有行为
--      （不改变其路由与计费），把空串解释为回退默认分组的职责交给运行期
--      （见 model.Token.EffectiveGroupName），迁移本身不改动任何历史语义；
--   2) 列名用 group_name 而不是 group：group 是 SQL 保留字，
--      直接用作列名会让部分语句需要额外转义，徒增踩坑；
--   3) 不引入外键约束（与 0011 一致）：历史部署里可能存在尚未登记的分组名，
--      加外键会让已有数据或启动失败。运行期遇到未知分组由 server 层拦截。
--
-- 兼容性：
--   本列 NOT NULL + 常量默认值，SQLite 允许对已有表直接 ADD COLUMN；
--   已有令牌行会一次性获得空串默认值，转发与计费行为与迁移前完全一致。

ALTER TABLE tokens ADD COLUMN group_name TEXT NOT NULL DEFAULT '';

-- 后台"按分组筛选令牌"用：group_name 的选择性不高，但令牌表通常只有几十到几千行，
-- 该索引的收益有限；保留它是为了与 owner_id / status 的筛选索引保持一致，
-- 且未来按分组做批量运维（如"把某分组的令牌全部禁用"）时会真正派上用场。
CREATE INDEX IF NOT EXISTS idx_tokens_group_name ON tokens (group_name);
